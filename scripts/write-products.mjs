function round1(n) {
  return Math.round(n * 10) / 10
}

function per100g(perServing, servingGrams) {
  const factor = 100 / servingGrams
  return {
    kcal: Math.round(perServing.kcal * factor),
    protein: round1(perServing.protein * factor),
    carbs: round1(perServing.carbs * factor),
    fat: round1(perServing.fat * factor),
  }
}

function shareAtLeast(grams, kcalPerGram, kcal, threshold) {
  if (!(kcal > 0)) return false
  const left = Math.round(grams * kcalPerGram * 1000)
  const right = Math.round(threshold * kcal * 1000)
  return left >= right
}

function flags(m) {
  return {
    hp: m.protein >= 10 && shareAtLeast(m.protein, 4, m.kcal, 0.2),
    hc: shareAtLeast(m.carbs, 4, m.kcal, 0.55),
    hf: shareAtLeast(m.fat, 9, m.kcal, 0.5),
  }
}

const products = raw.map((item) => ({
  id: item.id,
  name: item.name,
  brand: item.brand,
  size: item.size,
  priceAED: item.priceAED,
  category: item.category,
  emoji: item.emoji,
  servingSize: item.servingSize,
  servingGrams: item.servingGrams,
  netWeightG: item.netWeightG,
  perServing: item.perServing,
  per100g: per100g(item.perServing, item.servingGrams),
}))

const groups = { hp: [], hc: [], hf: [], none: [] }
for (const product of products) {
  const mark = flags(product.perServing)
  const value =
    (product.perServing.protein * (product.netWeightG / product.servingGrams)) /
    product.priceAED
  const row = `${product.id}  ${value.toFixed(2)} g/AED`
  if (!mark.hp && !mark.hc && !mark.hf) groups.none.push(row)
  if (mark.hp) groups.hp.push(row)
  if (mark.hc) groups.hc.push(row)
  if (mark.hf) groups.hf.push(row)
}

if (products.length !== 40) {
  throw new Error(`Expected 40 products, got ${products.length}`)
}

writeFileSync(new URL("../data/products.json", import.meta.url), JSON.stringify(products, null, 2) + "\n")

